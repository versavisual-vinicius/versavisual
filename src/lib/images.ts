const LOCAL_IMAGE_FALLBACK = "/images/foto-a-producao-nao-falha.webp"

export function img(id: string, w = 1200, h?: number): string {
  if (!id) return ""
  if (id.startsWith("/") || id.startsWith("http") || id.startsWith("data:")) {
    return id
  }
  return LOCAL_IMAGE_FALLBACK
}

export function getImageAlt(
  src: string,
  contextTitle = "Produção audiovisual",
): string {
  if (!src) return "Produção audiovisual autoral VERSAVISUAL"
  const filename = src.split("/").pop() || ""
  const cleanName = decodeURIComponent(filename)
    .replace(/\.[^/.]+$/, "")
    .replace(/[-_]+/g, " ")
    .replace(/\d+$/, "")
    .trim()
  if (cleanName && cleanName.length > 3) {
    return `${cleanName} — ${contextTitle} VERSAVISUAL`
  }
  return `${contextTitle} — Direção audiovisual VERSAVISUAL`
}

